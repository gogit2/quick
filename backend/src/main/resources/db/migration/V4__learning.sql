CREATE TABLE learning_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(2000) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE learning_milestone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learning_card_id BIGINT NOT NULL REFERENCES learning_card(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    done BOOLEAN NOT NULL DEFAULT FALSE,
    target_date DATE NULL,
    completed_at TIMESTAMP NULL
);

CREATE TABLE learning_note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learning_card_id BIGINT NOT NULL REFERENCES learning_card(id) ON DELETE CASCADE,
    text VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_learning_milestone_card ON learning_milestone (learning_card_id);
CREATE INDEX idx_learning_note_card ON learning_note (learning_card_id);
